print("Operadores de comparacion - Signos vitales")

temperatura1 = float(input("Temperatura paciente 1: "))
temperatura2 = float(input("Temperatura paciente 2: "))

print(temperatura1, "==", temperatura2, temperatura1 == temperatura2)
print(temperatura1, "!=", temperatura2, temperatura1 != temperatura2)
print(temperatura1, ">", temperatura2, temperatura1 > temperatura2)
print(temperatura1, "<", temperatura2, temperatura1 < temperatura2)
print(temperatura1, ">=", temperatura2, temperatura1 >= temperatura2)
print(temperatura1, "<=", temperatura2, temperatura1 <= temperatura2)
